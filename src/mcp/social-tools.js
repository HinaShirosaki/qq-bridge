const SLIM_MESSAGE_PATHS = new Set(['/api/socialV2/unread', '/api/socialV2/recent', '/api/socialV2/wait', '/api/socialV2/my-recent']);

// Keep console/API responses intact; only the model-facing MCP view is compacted.
export function compactAgentResponse(requestPath, data) {
  if (!data || typeof data !== 'object' || data.ok === false) return data;
  const pathname = requestPath.split('?')[0];
  if (pathname === '/api/socialV2/mark-read') {
    // Confirmation is enough; qq_social_state still exposes the full config.
    const { wakeConfig, wakeSafety, ...confirmation } = data;
    return confirmation;
  }
  if (pathname === '/api/socialV2/wake-config') {
    // The model just sent this config; echo only what the bridge may have normalised.
    const { wakeConfig, wakeSafety, ...confirmation } = data;
    const speakerIds = wakeConfig?.triggers?.speakerIds;
    return {
      ...confirmation,
      sleepUntil: wakeConfig?.sleepUntil ?? null,
      ...(speakerIds?.length ? { speakerIds } : {}),
      wakeGuaranteed: wakeSafety?.guaranteed,
    };
  }
  // Only chat-history endpoints: forward-message handlers read messages[].media themselves.
  if (!SLIM_MESSAGE_PATHS.has(pathname)) return data;
  const out = { ...data };
  for (const field of ['messages', 'newMessages']) {
    if (Array.isArray(out[field])) out[field] = out[field].map(slimMessage);
  }
  return out;
}

// Stored messages repeat the text three times (text/plain/tail), carry image URLs the model
// never needs (qq_get_message_images looks media up by messageId), and many false/empty flags.
// Every copy stays in the conversation history and is replayed on each later model step.
export function slimMessage(m) {
  if (!m || typeof m !== 'object') return m;
  const { plain, tail, media, ownerLabel, ...rest } = m;
  const out = {};
  for (const [k, v] of Object.entries(rest)) {
    if (v === false || v === null || v === undefined || v === '' || (Array.isArray(v) && v.length === 0)) continue;
    out[k] = v;
  }
  if (out.isSelf) delete out.isOwner; // self messages are stored with isOwner: true, which misleads
  if (plain && plain !== rest.text) out.plain = plain;
  // tail differs from plain only when the original message exceeded 200 characters.
  if (tail && tail !== (plain ?? rest.text)) out.tail = tail;
  return out;
}
